export const LEGAL_ROUTES = new Set(Object.keys(LEGAL_DOCS));

/** Full page for #offer, #privacy and #refund. onBack() leaves the documents. */
export function renderLegal(root, id, { onBack }) {
  const doc = LEGAL_DOCS[id];
  const article = h("article", { class: "legal-doc" });
  article.innerHTML = `<h1>${doc.title}</h1>${doc.html}`;   // our own static text
  const page = h("div", { class: "legal-page" },
    h("header", { class: "legal-head" },
      h("button", { class: "icon-btn", type: "button", "aria-label": "Back", onclick: onBack }, icon("back")),
      h("div", { class: "brand small" }, h("img", { src: "logo.png", alt: "", width: "26", height: "26" }), h("span", {}, "Veora")),
      h("nav", { class: "legal-tabs", "aria-label": "Documents" },
        Object.entries(LEGAL_DOCS).map(([key, d]) => h("a", { href: `#${key}`, class: key === id ? "active" : "", "aria-current": key === id ? "page" : null }, d.title)))),
    h("main", { class: "legal-main" }, article));
  root.replaceChildren(page);
  scrollTo(0, 0);
  return () => page.remove();
}
